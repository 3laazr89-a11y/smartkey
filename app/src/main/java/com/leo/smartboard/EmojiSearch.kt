    fun allSearchableEmojis(): List<String> = terms.keys.toList()

    fun search(query: String, emojis: List<String>): List<String> {
        val q = normalize(query)
        if (q.isBlank()) return emptyList()
        val queryTokens = q.split(' ').filter { it.isNotBlank() }
        return emojis.distinct().filter { emoji ->
            if (emoji.contains(query)) return@filter true
            val labels = terms[emoji] ?: return@filter false
            val normalizedLabels = normalize(labels)
            val labelTokens = labels.split(' ').map(::normalize)
            normalizedLabels.contains(q) || queryTokens.all { queryToken -> labelTokens.any { it.contains(queryToken) } }
        }
    }

    private fun normalize(value: String): String = buildString {
        for (ch in value.trim().lowercase(Locale.ROOT)) {
            if (Character.getType(ch) == Character.NON_SPACING_MARK.toInt() || ch == 'ـ') continue
            append(when (ch) {
                'أ', 'إ', 'آ', 'ٱ' -> 'ا'
                'ى' -> 'ي'
                'ة' -> 'ه'
                else -> ch
            })
        }
    }
